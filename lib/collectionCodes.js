/**
 * Valida um código de coleção.
 * @param {string} code 
 * @returns {{ valid: boolean, code: string, isCanonical: boolean }}
 */
export function validateCollectionCode(code = "") {
  if (typeof code !== "string" || !code.trim()) {
    return { valid: false, code: "COL-00-MULTI", isCanonical: false };
  }

  const clean = code.trim().toUpperCase();
  const isCanonical = CANONICAL_COLLECTION_CODES.includes(clean);
  const resolved = resolveCollectionCode(clean);

  return {
    valid: isCanonical || resolved !== "COL-00-MULTI",
    code: resolved,
    isCanonical
  };
}

