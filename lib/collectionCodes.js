/**
 * Resolve qualquer alias legado ou string de código para seu código canônico.
 * Preserva novos códigos e nomes de franquias customizadas sem forçar para MULTIVERSE.
 * @param {string} rawInput 
 * @returns {string} Código canônico ou sanitizado (ex: COL-04-ATLA)
 */
export function resolveCollectionCode(rawInput = "") {
  if (typeof rawInput !== "string" || !rawInput.trim()) {
    return "COL-00-MULTI";
  }

  const clean = rawInput.trim().toUpperCase();

  // Se for explicitamente genérico / multiverso
  if (["MULTIVERSE", "MULTI", "COL-00-MULTI", "DEFAULT", "GENERIC"].includes(clean)) {
    return "COL-00-MULTI";
  }

  // Se já for um código canônico válido
  if (CANONICAL_COLLECTION_CODES.includes(clean)) {
    return clean;
  }

  // Se for um alias mapeado
  if (LEGACY_ALIASES[clean]) {
    return LEGACY_ALIASES[clean];
  }

  // Procura por correspondência parcial no alias ou código canônico
  for (const [alias, canonical] of Object.entries(LEGACY_ALIASES)) {
    if (alias !== "MULTI" && alias !== "DEFAULT" && (clean.includes(alias) || alias.includes(clean))) {
      return canonical;
    }
  }

  for (const code of CANONICAL_COLLECTION_CODES) {
    if (code !== "COL-00-MULTI" && (code.includes(clean) || clean.includes(code))) {
      return code;
    }
  }

  // Se o código já inicia com COL- ou parece ser um código de coleção válido
  if (clean.startsWith("COL-") || (clean.length >= 2 && !clean.includes(" "))) {
    return clean;
  }

  // Se for um nome textual de franquia, gera um código estruturado sem cair em MULTI
  const formattedCode = `COL-${clean.replace(/[^A-Z0-9]/g, "").slice(0, 10)}`;
  return formattedCode.length > 4 ? formattedCode : "COL-00-MULTI";
}

